import streamlit as st
import pandas as pd
import numpy as np
import joblib
import os

# --- Konfigurasi Halaman ---
st.set_page_config(page_title="Prediksi Diabetes", layout="centered")

# --- Load Model dan Preprocessor dengan Caching ---
@st.cache_resource
def load_artifacts():
    """Memuat model, scaler, dan feature names."""
    # Cek apakah semua file yang diperlukan ada
    required_files = ['best_diabetes_model.pkl', 'scaler.pkl', 'feature_names.pkl']
    for file in required_files:
        if not os.path.exists(file):
            st.error(f"File {file} tidak ditemukan! Pastikan semua file model tersedia.")
            st.stop()

    model = joblib.load('best_diabetes_model.pkl')
    scaler = joblib.load('scaler.pkl')
    feature_names = joblib.load('feature_names.pkl')
    return model, scaler, feature_names

try:
    model, scaler, feature_names = load_artifacts()
except Exception as e:
    st.error(f"Gagal memuat model: {e}")
    st.stop()

# --- Header Aplikasi ---
st.title("🩺 Aplikasi Prediksi Risiko Diabetes")
st.markdown("Masukkan data pasien untuk mengetahui risiko diabetes berdasarkan model machine learning.")

# --- Form Input Data ---
with st.form("prediction_form"):
    st.subheader("Data Pasien")
    col1, col2 = st.columns(2)

    with col1:
        gender = st.selectbox("Jenis Kelamin", options=[0, 1], format_func=lambda x: "Perempuan" if x==0 else "Laki-laki")
        age = st.number_input("Usia (tahun)", min_value=0, max_value=120, value=30)
        hypertension = st.selectbox("Riwayat Hipertensi", options=[0, 1], format_func=lambda x: "Tidak" if x==0 else "Ya")
        heart_disease = st.selectbox("Riwayat Penyakit Jantung", options=[0, 1], format_func=lambda x: "Tidak" if x==0 else "Ya")
        smoking_history = st.selectbox("Riwayat Merokok", options=[0, 1, 2, 3, 4],
                                       format_func=lambda x: ["Tidak pernah", "Tidak saat ini", "Mantan Perokok", "Pernah merokok", "Perokok aktif"][x])
    with col2:
        bmi = st.number_input("Indeks Massa Tubuh (BMI)", min_value=0.0, max_value=100.0, value=25.0, step=0.1)
        hbA1c_level = st.number_input("Kadar HbA1c (%)", min_value=0.0, max_value=20.0, value=5.5, step=0.1)
        blood_glucose_level = st.number_input("Kadar Gula Darah (mg/dL)", min_value=0, max_value=500, value=120)
        # Input untuk ras (one-hot encoding)
        race_african = st.selectbox("Ras: Afrika-Amerika", options=[0,1], format_func=lambda x: "Ya" if x==1 else "Tidak")
        race_asian = st.selectbox("Ras: Asia", options=[0,1], format_func=lambda x: "Ya" if x==1 else "Tidak")
        race_caucasian = st.selectbox("Ras: Kaukasia", options=[0,1], format_func=lambda x: "Ya" if x==1 else "Tidak")
        race_hispanic = st.selectbox("Ras: Hispanik", options=[0,1], format_func=lambda x: "Ya" if x==1 else "Tidak")

    # Tombol submit
    submitted = st.form_submit_button("🔍 Prediksi Risiko Diabetes")

# --- Proses Prediksi ---
if submitted:
    # Buat dictionary input yang sesuai dengan urutan fitur saat training
    input_dict = {
        'gender': gender,
        'age': age,
        'hypertension': hypertension,
        'heart_disease': heart_disease,
        'smoking_history': smoking_history,
        'bmi': bmi,
        'hbA1c_level': hbA1c_level,
        'blood_glucose_level': blood_glucose_level,
        'race_AfricanAmerican': race_african,
        'race_Asian': race_asian,
        'race_Caucasian': race_caucasian,
        'race_Hispanic': race_hispanic
    }

    # Tambahkan fitur race_Other jika tidak ada (isi 0)
    if 'race_Other' in feature_names and 'race_Other' not in input_dict:
        input_dict['race_Other'] = 0

    # Konversi ke DataFrame dengan urutan fitur yang benar
    input_df = pd.DataFrame([input_dict])[feature_names]

    # Standardisasi fitur numerik (hanya kolom yang perlu)
    numeric_cols = ['age', 'bmi', 'hbA1c_level', 'blood_glucose_level']
    input_df[numeric_cols] = scaler.transform(input_df[numeric_cols])

    # Lakukan prediksi
    prediction = model.predict(input_df)[0]
    probability = model.predict_proba(input_df)[0][1]

    # Tampilkan hasil
    st.subheader("📊 Hasil Prediksi:")
    if prediction == 1:
        st.error(f"⚠️ **Terindikasi Diabetes**\n\nProbabilitas: {probability:.2%}")
        st.info("⚠️ Disarankan untuk melakukan konsultasi lebih lanjut dengan tenaga medis.")
    else:
        st.success(f"✅ **Tidak Terindikasi Diabetes**\n\nProbabilitas: {probability:.2%}")
        st.info("✅ Risiko rendah, namun tetap jaga pola hidup sehat.")